//
//  MQAlgorithmTests.swift
//  xdripTests
//
//  Expected values come from running the unchanged JugglucoNG Kotlin (`MQAlgorithm`, `MQBootstrapSeed`)
//  on the JVM: the ramp of the raw current, the vendor calculation with its smoothing, K and B and the
//  clamps, the Float round trip of K, the sensitivity normalisation and the first reference of the
//  vendor's startup. The fixtures of JugglucoNG's evidence notes (packet 345 of the 2026-09-14 trace,
//  the packet 24 first reference) are among them. The decimal truncation helper is additionally
//  cross-checked against Python's `decimal` (ROUND_DOWN) and `numpy.float32` over several hundred
//  thousand random values. Never compared with a real sensor.
//

import XCTest
@testable import xdrip

final class MQAlgorithmTests: XCTestCase {

    private typealias V = MQVectorSupport

    // MARK: - ramp of the raw current

    func testAdjustSampleCurrentVectors() {
        for line in MQAlgorithmVectors.adjust {
            let f = V.fields(line)
            let adjusted = MQAlgorithm.adjustSampleCurrent(
                algorithmVersion: Int(f[1]) ?? 0,
                packetIndex: V.d(f[2]),
                sampleCurrent: V.d(f[3]),
                packages: V.d(f[4]),
                multiplier: V.d(f[5])
            )
            XCTAssertEqual(V.bits(adjusted), f[6], line)
        }
    }

    // MARK: - calculation

    func testCalculateVectors() {
        for line in MQAlgorithmVectors.calculate {
            let f = V.fields(line)
            let version = Int(f[1]) ?? 0
            let initTime = V.d(f[2])
            let packet = V.d(f[3])
            let current = V.d(f[4])
            let previous = V.d(f[5])
            let k = V.d(f[6])
            let reference = V.d(f[7])
            let b = V.d(f[8])
            let packages = V.d(f[9])
            let multiplier = V.d(f[10])

            let values = MQAlgorithm.calculate(
                algorithmVersion: version, initTimeMinutes: initTime, packetIndex: packet, sampleCurrent: current,
                previousReviseCurrent2: previous, kValue: k, referenceBgTimes10Mmol: reference, bValue: b,
                packages: packages, multiplier: multiplier
            )
            XCTAssertEqual(values.map { V.bits($0) }.joined(separator: ","), f[11], line)

            let result = MQAlgorithm.calculateResult(
                algorithmVersion: version, initTimeMinutes: initTime, packetIndex: packet, sampleCurrent: current,
                previousReviseCurrent2: previous, kValue: k, referenceBgTimes10Mmol: reference, bValue: b,
                packages: packages, multiplier: multiplier
            )
            XCTAssertEqual(result.glucoseTimes10Mmol, Int(f[12]), line)
            XCTAssertEqual(result.mgdlTimes10, Int(f[13]), line)
            XCTAssertEqual(V.bits(result.mgdl), f[14], line)
            XCTAssertEqual(V.bits(result.mmol), f[15], line)
            XCTAssertEqual(V.bits(result.glucoseMmol), f[16], line)
        }
    }

    func testTheEvidencePacket345() throws {
        // JugglucoNG's notes: previous 104, raw 449, K 20.12, B 2 gives processed current 110 and 5.5 mmol/L
        let result = MQAlgorithm.calculateResult(
            algorithmVersion: 1, initTimeMinutes: 5000, packetIndex: 345, sampleCurrent: 449, previousReviseCurrent2: 104,
            kValue: 20.12, referenceBgTimes10Mmol: 0, bValue: 2, packages: 720, multiplier: 1.0
        )
        XCTAssertEqual(result.reviseCurrent2, 110)
        XCTAssertEqual(result.glucoseTimes10Mmol, 55)
        XCTAssertEqual(result.kValue, 20.12)
        XCTAssertEqual(result.bValue, 2)
    }

    // MARK: - decimal parameters

    func testDecimalParameterVectors() {
        for line in MQAlgorithmVectors.decimal {
            let f = V.fields(line)
            // Kotlin prints the smallest float as "1.4E-45" (two digits), Swift as "1e-45": the one
            // value whose shortest text differs between the two languages is not used by the driver
            if f[1] == "00000001" { continue }
            XCTAssertEqual(V.bits(MQAlgorithm.decimalParameter(V.f(f[1]))), f[2], line)
        }
    }

    func testDecimalParameterOfNonFiniteValues() {
        XCTAssertTrue(MQAlgorithm.decimalParameter(.nan).isNaN)
        XCTAssertEqual(MQAlgorithm.decimalParameter(.infinity), .infinity)
        XCTAssertEqual(MQAlgorithm.decimalParameter(-.infinity), -.infinity)
        // the Kotlin printer's NaN / Infinity line
        let f = V.fields(MQAlgorithmVectors.decimalNonFinite[0])
        XCTAssertEqual(f[1], "7FF8000000000000")
        XCTAssertEqual(V.bits(MQAlgorithm.decimalParameter(.infinity)), f[2])
    }

    func testKSurvivesStoreAndRestoreCycles() throws {
        // JugglucoNG's regression: K 29.41 became 29.40 when a stored Float was widened to Double before
        // the decimal truncation; 100 save / restore / calculate cycles keep it
        let f = V.fields(try XCTUnwrap(MQAlgorithmVectors.kLoop.first))
        var storedK: Float = 29.41
        var previous = 100.0
        var distinct = [String]()
        for offset in 0..<100 {
            let result = MQAlgorithm.calculateResult(
                algorithmVersion: 1, initTimeMinutes: 744.0 + Double(offset) * 3, packetIndex: 248.0 + Double(offset),
                sampleCurrent: 103.0, previousReviseCurrent2: previous, kValue: MQAlgorithm.decimalParameter(storedK),
                referenceBgTimes10Mmol: 0.0, bValue: 2.0, packages: 720.0, multiplier: 1.0
            )
            let text = V.bits(result.kValue)
            if !distinct.contains(text) { distinct.append(text) }
            storedK = Float(result.kValue)
            previous = result.reviseCurrent2
        }
        XCTAssertEqual(distinct.joined(separator: ","), f[1])
        XCTAssertEqual(V.bits(storedK), f[2])
        XCTAssertEqual(V.bits(previous), f[3])
    }

    func testRoundDown2TruncatesInsteadOfRounding() {
        XCTAssertEqual(MQAlgorithm.roundDown2(29.419999), 29.41)
        XCTAssertEqual(MQAlgorithm.roundDown2(29.999), 29.99)
        XCTAssertEqual(MQAlgorithm.roundDown2(-29.999), -29.99)
        XCTAssertEqual(MQAlgorithm.roundDown2(0.009), 0)
        XCTAssertEqual(MQAlgorithm.roundDown2(-0.009).sign, .plus)
        XCTAssertEqual(MQAlgorithm.roundDown2(5), 5)
        XCTAssertEqual(MQAlgorithm.roundDown2(1e-5), 0)
        XCTAssertEqual(MQAlgorithm.roundDown2(1.5e20), 1.5e20)
        // Kotlin throws for these; the port returns them unchanged
        XCTAssertTrue(MQAlgorithm.roundDown2(.nan).isNaN)
        XCTAssertEqual(MQAlgorithm.roundDown2(.infinity), .infinity)
    }

    func testDecimalDigitsAgainstPython() {
        // expected values from Python: float(Decimal(repr(x)).quantize(Decimal('0.01'), ROUND_DOWN))
        for line in MQAlgorithmVectors.truncation {
            let f = V.fields(line)
            XCTAssertEqual(V.bits(MQAlgorithm.roundDown2(V.d(f[1]))), f[2], line)
        }
    }

    func testDecimalDigitsParsing() throws {
        let plain = try XCTUnwrap(MQDecimalDigits("123.456"))
        XCTAssertEqual(plain.digits, [1, 2, 3, 4, 5, 6])
        XCTAssertEqual(plain.pointPosition, 3)
        XCTAssertFalse(plain.negative)

        let small = try XCTUnwrap(MQDecimalDigits("-0.00123"))
        XCTAssertEqual(small.digits, [1, 2, 3])
        XCTAssertEqual(small.pointPosition, -2)
        XCTAssertTrue(small.negative)

        let exponent = try XCTUnwrap(MQDecimalDigits("1.5e+20"))
        XCTAssertEqual(exponent.digits, [1, 5])
        XCTAssertEqual(exponent.pointPosition, 21)

        let tiny = try XCTUnwrap(MQDecimalDigits("1e-05"))
        XCTAssertEqual(tiny.digits, [1])
        XCTAssertEqual(tiny.pointPosition, -4)

        let zero = try XCTUnwrap(MQDecimalDigits("0.0"))
        XCTAssertEqual(zero.digits, [])
        XCTAssertEqual(zero.doubleValue(), 0)

        XCTAssertNil(MQDecimalDigits("abc"))
        XCTAssertNil(MQDecimalDigits(""))
        XCTAssertNil(MQDecimalDigits("1e"))
    }

    // MARK: - factory sensitivity

    func testNormalizeSensitivityVectors() {
        for line in MQAlgorithmVectors.normalize {
            let f = V.fields(line)
            let raw: Float? = f[1] == "nil" ? nil : V.f(f[1])
            let scale = V.optionalInt(f[2])
            XCTAssertEqual(V.bits(MQBootstrapSeed.normalizeSensitivity(raw: raw, transmitter10: scale)), f[3], line)
        }
    }

    func testInitialReferenceVectors() {
        for line in MQAlgorithmVectors.initial {
            let f = V.fields(line)
            let result = MQBootstrapSeed.initialReference(
                algorithmVersion: Int(f[1]) ?? 0,
                packetIndex: Int(f[2]) ?? 0,
                sampleCurrent: Int(f[3]) ?? 0,
                previousProcessed: V.d(f[4]),
                sensitivity: V.d(f[5]),
                packages: Int(f[6]) ?? 0,
                multiplier: V.d(f[7])
            )
            if f[8] == "nil" {
                XCTAssertNil(result, line)
                continue
            }
            guard let r = result else {
                XCTFail("expected a first reference for \(line)")
                continue
            }
            let text = "\(r.glucoseTimes10Mmol),\(V.bits(r.reviseCurrent2)),\(V.bits(r.kValue)),\(V.bits(r.bValue)),\(V.bits(r.referenceBgTimes10Mmol))"
            XCTAssertEqual(text, f[8], line)
        }
    }

    func testTheDocumentedFirstReference() throws {
        // JugglucoNG's evidence notes: sensitivity 2.93 on a x10 transmitter is 29.3; at packet 24 the
        // raw current 175 minus the offset 2 is 173 and gives the reference 59 (5.9 mmol/L); solving K
        // from that reference gives 29.32
        let f = V.fields(try XCTUnwrap(MQAlgorithmVectors.documentedFixture.first))
        let sensitivity = try XCTUnwrap(MQBootstrapSeed.normalizeSensitivity(raw: 2.93, transmitter10: 1))
        XCTAssertEqual(sensitivity, 29.3)
        let seed = try XCTUnwrap(MQBootstrapSeed.initialReference(
            algorithmVersion: 1, packetIndex: 24, sampleCurrent: 175, previousProcessed: 0,
            sensitivity: Double(String(sensitivity)) ?? 0, packages: 720, multiplier: 1.0
        ))
        let calibrated = MQAlgorithm.calculateResult(
            algorithmVersion: 1, initTimeMinutes: 24, packetIndex: 24, sampleCurrent: 175, previousReviseCurrent2: 0,
            kValue: 0, referenceBgTimes10Mmol: Double(seed.glucoseTimes10Mmol), bValue: 0, packages: 720, multiplier: 1.0
        )
        XCTAssertEqual(seed.reviseCurrent2, 173.0)
        XCTAssertEqual(seed.glucoseTimes10Mmol, 59)
        XCTAssertEqual(calibrated.kValue, 29.32)
        XCTAssertEqual(calibrated.glucoseTimes10Mmol, 59)
        XCTAssertEqual(calibrated.glucoseMmol, 5.9)
        XCTAssertEqual(V.bits(calibrated.mgdl), f[6])
    }

    func testTheFirstReferenceNeedsAKnownScale() {
        XCTAssertNil(MQBootstrapSeed.normalizeSensitivity(raw: 2.93, transmitter10: nil))
        XCTAssertNil(MQBootstrapSeed.normalizeSensitivity(raw: 2.93, transmitter10: 2))
        XCTAssertEqual(MQBootstrapSeed.normalizeSensitivity(raw: 2.93, transmitter10: 0), 2.93)
        XCTAssertEqual(MQBootstrapSeed.normalizeSensitivity(raw: 2.93, transmitter10: 1), 29.3)
    }

    // MARK: - references and results

    func testReferenceConversionVectors() {
        for line in MQAlgorithmVectors.referenceConversion {
            let f = V.fields(line)
            let mgdl = Int(f[1]) ?? 0
            XCTAssertEqual(V.bits((Double(mgdl) / MQConstants.mmolToMgdl) * 10.0), f[2], line)
        }
    }

    func testResultAccessorVectors() {
        for line in MQAlgorithmVectors.resultAccessors {
            let f = V.fields(line)
            let tenths = Int(f[1]) ?? 0
            let result = MQAlgorithm.Result(
                packetIndex: 1, sampleCurrent: 1, reviseCurrent2: 1, previousReviseCurrent2: 1, kValue: 1,
                referenceBgTimes10Mmol: 1, bValue: 1, glucoseTimes10Mmol: tenths, glucoseMmol: Double(tenths) / 10.0
            )
            XCTAssertEqual(result.mgdlTimes10, Int(f[2]), line)
            XCTAssertEqual(V.bits(result.mgdl), f[3], line)
            XCTAssertEqual(V.bits(result.mmol), f[4], line)
        }
    }

    func testKotlinNumberHelpers() {
        XCTAssertEqual(mqKotlinInt(2.9), 2)
        XCTAssertEqual(mqKotlinInt(-2.9), -2)
        XCTAssertEqual(mqKotlinInt(.nan), 0)
        XCTAssertEqual(mqKotlinInt(1e30), Int(Int32.max))
        XCTAssertEqual(mqKotlinInt(-1e30), Int(Int32.min))
        XCTAssertEqual(mqKotlinRound(2.5), 3)
        XCTAssertEqual(mqKotlinRound(-2.5), -2)
        XCTAssertEqual(mqKotlinRound(2.4999), 2)
        XCTAssertEqual(mqKotlinRound(1e30), Int(Int32.max))
        XCTAssertEqual(mqKotlinRound(.nan), 0)
    }
}

